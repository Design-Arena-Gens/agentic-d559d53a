      <section>
        <h2>Discussion</h2>
        <p>
          This study reveals that futsal-specific fatigue reallocates landing
          loads in elite female players toward distal joint structures when
          adopting ankle-dominant mechanics, while hip-dominant strategies
          sustain proximal absorption at the cost of frontal-plane knee control.
          These findings broaden previous soccer and basketball observations by
          highlighting strategy-dependent fatigue responses in a futsal-specific
          context (Cortes et al., 2012; McLean et al., 2007).
        </p>
        <p>
          The 9.4% increase in vGRF under ankle-dominant fatigue aligns with
          reports that limited hip flexion elevates tibiofemoral loading
          (Taylor et al., 2016). Reduced ankle dorsiflexion under fatigue may
          reflect impaired eccentric control of the triceps surae, a known
          consequence of repeated-sprint activity (Nédélec et al., 2012). From an
          injury prevention standpoint, sustaining hip contributions appears
          beneficial, yet the concomitant 2.1° rise in knee valgus under
          hip-dominant fatigue echoes ACL risk factors observed in female
          athletes (Benjaminse et al., 2019).
        </p>
        <p>
          The greater deterioration in TTS among ankle-dominant landings suggests
          compromised postural integration, consistent with sensorimotor fatigue
          literature (Fort-Vanmeerhaeghe et al., 2016). Coaches should therefore
          monitor balance restoration drills under fatigue to preserve
          proprioceptive acuity. Integrating wearable player-load indices and
          session rating of perceived exertion (sRPE) may further individualize
          fatigue management (Silva et al., 2019).
        </p>
        <p>
          Practical application involves implementing hybrid landing progression
          drills that cue hip flexion while maintaining knee alignment through
          external focus instructions and real-time biofeedback (Padua et al.,
          2009). Inclusion of unilateral strength, eccentric calf conditioning,
          and perturbation training may help preserve joint-specific stiffness
          under late-match fatigue (Pappas et al., 2007).
        </p>
      </section>

